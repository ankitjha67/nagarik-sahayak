def _domicile(state: str, section="Address"):
    """Residency proof block — the gate on every State scheme."""
    return [
        _f("domicile_certificate_number", f"{state} Domicile / Residence Certificate Number",
           f"{state} अधिवास प्रमाण पत्र संख्या", section=section,
           profile_key="domicile_certificate_number", required=False),
        _f("residency_years", "Years of Residence in the State", "राज्य में निवास के वर्ष",
           "number", section=section, profile_key="residency_years", required=False),
    ]


def _ration_fields(section="Economic Details"):
    return [
        _f("ration_card_number", "Ration Card Number", "राशन कार्ड संख्या",
           section=section, profile_key="ration_card_number", required=False),
        _f("ration_card_type", "Ration Card Type", "राशन कार्ड का प्रकार", "select",
           section=section, profile_key="ration_card_type", required=False,
           options=["Antyodaya (AAY)", "Priority Household (PHH)", "BPL", "APL", "None"]),
    ]


