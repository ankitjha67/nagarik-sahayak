"""State Government schemes.

Most welfare money an Indian citizen can actually claim is disbursed by a State,
not by the Union — a woman in Madhya Pradesh is far more likely to be drawing
Ladli Behna than any central transfer. A catalog that carried only central
schemes would tell most users they qualify for nothing.

Two things are handled carefully here:

**Domicile.** Every scheme below is restricted to residents of one State. The
rule is expressed as ``state == <State>`` so the eligibility engine refuses a
scheme the citizen genuinely cannot claim, rather than raising hope and then
failing at the counter. ``state`` on the entry is the issuing State; the
``state`` profileKey is the citizen's own.

**Portals, not PDFs.** Nearly all of these are online-only: the application is
made on a State portal, at a CSC, or through a camp, and no department
publishes a downloadable form. ``official_pdf_url`` is therefore empty for
most entries. Inventing a URL that 404s would send a citizen looking for a
document that does not exist, so the field is left blank and the portal is
named instead.

Amounts and thresholds move with State budgets. Where a figure is stated it
was the published figure at the time of writing; ``summary`` says so in words
so a citizen reads the criterion rather than trusting a number that may have
been revised.
"""
from __future__ import annotations

