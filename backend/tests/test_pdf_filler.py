# ─── Helper: create test PDFs ───

def _create_text_pdf(text: str = "Name: ________") -> str:
    from fpdf import FPDF
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", size=12)
    for line in text.split("\n"):
        pdf.cell(0, 10, text=line, new_x="LMARGIN", new_y="NEXT")
    tmp = tempfile.NamedTemporaryFile(suffix=".pdf", delete=False)
    pdf.output(tmp.name)
    return tmp.name


# ─── Value formatting ───

class TestValueFormatting:
    def test_aadhaar_is_masked_even_on_an_official_form(self):
        """This used to assert the opposite, and the assertion was the bug.

        The printed form asks for all twelve digits, so writing all twelve felt
        like the helpful thing to do. But Aadhaar Act s29(4) makes publishing
        an Aadhaar number an offence, and this file is generated by the
        application, stored encrypted, and downloaded — putting the number
        somewhere the citizen no longer controls. The last four identify the
        record; the eight the citizen writes by hand on the counter copy are
        theirs to write.
        """
        from pdf_filler import _format_value_for_fill

        result = _format_value_for_fill("123456789012", "aadhaar")
        assert result != "123456789012"
        assert "9012" in result
        assert "12345678" not in result

    def test_a_filled_form_never_carries_twelve_digits(self):
        from dpdp.aadhaar_policy import contains_full_aadhaar
        from pdf_filler import _format_value_for_fill

        written = _format_value_for_fill("234567890124", "aadhaar")
        assert not contains_full_aadhaar({"written_to_pdf": written})

    def test_masking_survives_separators_the_citizen_typed(self):
        from pdf_filler import _format_value_for_fill

        for typed in ("2345 6789 0124", "2345-6789-0124", "234567890124"):
            assert "0124" in _format_value_for_fill(typed, "aadhaar")
            assert "23456789" not in _format_value_for_fill(typed, "aadhaar")

    def test_format_phone_10_digits(self):
        from pdf_filler import _format_value_for_fill
        result = _format_value_for_fill("9876543210", "phone")
        assert result == "9876543210"

    def test_format_phone_with_country_code(self):
        from pdf_filler import _format_value_for_fill
        result = _format_value_for_fill("919876543210", "phone")
        assert result == "9876543210"

    def test_format_date_iso(self):
        from pdf_filler import _format_value_for_fill
        result = _format_value_for_fill("1990-05-15", "date")
        assert result == "15/05/1990"

    def test_format_empty_value(self):
        from pdf_filler import _format_value_for_fill
        assert _format_value_for_fill("", "text") == ""
        assert _format_value_for_fill(None, "text") == ""

    def test_format_text_passthrough(self):
        from pdf_filler import _format_value_for_fill
        assert _format_value_for_fill("Raj Kumar", "text") == "Raj Kumar"


