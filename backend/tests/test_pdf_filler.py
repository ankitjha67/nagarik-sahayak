class TestLabelMatching:
    """Government forms print their own words, not the app's.

    The catalog calls a field "Full Name (as per Aadhaar)". The Haryana sports
    scholarship form calls it "Name of the Applicant". Matching only on the
    catalog label left the single most important field on the page blank.
    """

    def test_the_form_s_own_phrasing_is_recognised(self):
        from pdf_filler import FIELD_ALIASES

        assert "name of the applicant" in FIELD_ALIASES["name"]
        assert "bank's name" in FIELD_ALIASES["bank_name"]
        assert "aadhar no" in FIELD_ALIASES["aadhaar_number"], \
            "forms spell it Aadhar as often as Aadhaar"

    def test_relations_are_listed_before_the_bare_name(self):
        """"father's name" and "name" both match "Father's Name:". Resolving to
        the shorter one writes the applicant's own name onto their father's
        line, which is worse than leaving it blank."""
        from pdf_filler import _alias_hit

        hit = _alias_hit("4. father's name:", "father_husband_name", ())
        assert hit == "father's name"

    def test_search_handles_the_apostrophes_a_scan_produces(self):
        """OCR emits a typographic apostrophe, so a literal search finds
        nothing on a page that plainly reads Mother's Name."""
        from pdf_filler import _search_variants

        variants = _search_variants("mother's name")
        assert "mother’s name" in variants
        assert "mothers name" in variants


